#define HALF_ONE 0x3C00u
#define BC6H_RESERVED_MODE 0x13u

static void test_bc6h(void) {
  for (uint32_t v = 0; v < sizeof(k_bc6h) / sizeof(k_bc6h[0]); v++) {
    uint16_t out[BC7_TEXELS][4];
    bc6h_decode_block(k_bc6h[v].block, false, out);
    for (uint32_t t = 0; t < BC7_TEXELS; t++) {
      bool same = out[t][3] == HALF_ONE;
      for (uint32_t c = 0; c < 3u; c++) same = same && out[t][c] == k_bc6h[v].rgb[t * 3u + c];
      if (!same) {
        fprintf(stderr, "[bc7_test] BC6H vector %u texel %u differs\n", v, t);
        CHECK(0);
        break;
      }
    }
  }
  uint8_t reserved[BC7_BLOCK_BYTES];
  memset(reserved, 0x5A, sizeof(reserved));
  reserved[0] = BC6H_RESERVED_MODE;
  uint16_t out[BC7_TEXELS][4];
  bc6h_decode_block(reserved, false, out);
  for (uint32_t t = 0; t < BC7_TEXELS; t++) CHECK(out[t][0] == 0 && out[t][1] == 0 && out[t][2] == 0 && out[t][3] == HALF_ONE);
}

int main(void) {
  test_bc6h();
  const uint32_t blocks = sizeof(k_bc7_blocks) / BC7_BLOCK_BYTES;
  for (uint32_t b = 0; b < blocks; b++) {
    uint8_t out[BC7_TEXELS][4];
    bc7_decode_block(k_bc7_blocks + b * BC7_BLOCK_BYTES, out);
    if (memcmp(out, k_bc7_texels + b * sizeof(out), sizeof(out)) != 0) {
      fprintf(stderr, "[bc7_test] block %u (mode %u) differs\n", b, b % 8u);
      CHECK(0);
    }
  }
  const uint8_t invalid[BC7_BLOCK_BYTES] = {0};
  uint8_t out[BC7_TEXELS][4];
  memset(out, 0xAA, sizeof(out));
  bc7_decode_block(invalid, out);
  for (uint32_t t = 0; t < BC7_TEXELS; t++) CHECK(out[t][0] == 0 && out[t][3] == 0);
  printf("[bc7_test] passed\n");
  return 0;
}
